import numpy as np

# ============ 第 1 题：剥皮公式（4 维）============
# 目标：看到 shape，就能说出"写几个索引后剩什么"。
x = np.arange(2 * 3 * 4 * 5).reshape(2, 3, 4, 5)
print(x.shape)                # 预测: (2, 3, 4, 5)
print(x[1].shape)             # 预测:(3,4,5)
print(x[0, 2].shape)          # 预测:(4,5)
print(x[1, 0, 3].shape)       # 预测:(5,)
print(x[1, 0, 3, 4])          # 预测: 79  (这里要写一个"数"，不是 shape)
#
# 反向题：一次要拿到 shape 为 (4, 5) 的结果，索引里该写几个数？
# 答：2个数

# ============ 第 2 题：stack 的 axis = 新维插在第几号 ============
a = np.array([[1, 2, 3],
              [4, 5, 6]])     # (2, 3)
b = a * 10                    # [[10,20,30],[40,50,60]]
print(a.shape)                              # 预测: (2, 3)
print(np.stack((a, b), axis=0).shape)       # 预测:(2,2,3)
print(np.stack((a, b), axis=1).shape)       # 预测:(2,2,3)
print(np.stack((a, b), axis=2).shape)       # 预测:(2,3,2)
print(np.stack((a, b), axis=-1).shape)      # 预测: (2,3,2) (想想它和上面哪一个相同)
print(np.stack((a, b), axis=2)[0, 1])       # 预测:  [2 20] (写值)
print(np.stack((a, b), axis=0)[1, 0, 1])    # 预测: 20  (写值)

# ============ 第 3 题：整数索引砍维 / 切片保维（混着来）============
z = np.arange(2 * 3 * 4).reshape(2, 3, 4)
print(z.shape)                # 预测: (2, 3, 4)
print(z[1].shape)             # 预测:(3,4)
print(z[1, 1:3].shape)        # 预测:(2,4)
print(z[:, 0, :].shape)       # 预测:(2,4)
print(z[..., 0].shape)        # 预测:(2,3)
print(z[1, ::-1, 1])          # 预测: 重点[21 17 13]  (写值)

# ============ 第 4 题：图像场景，把模型用起来 ============
# N = 2 张图，H = 4，W = 6，C = 3  →  这就是模型的输入形状 (N, H, W, C)
img = np.arange(2 * 4 * 6 * 3).reshape(2, 4, 6, 3).astype(np.uint8)
print(img.shape)                          # 预测: (2, 4, 6, 3)
print(img[0].shape)                       # 预测:(4,6,3)
print(img[0, ::2, :, 0].shape)            # 预测:(2,6)
print(img.mean(axis=(0, 1, 2)).shape)     # 预测:(3,)
#
# 反向题：一次要拿到 shape 为 (2, 3) —— 也就是"每张图只取某一个像素的 3 个通道值"。
#   ① 索引该怎么写？答：img[:,0,1,:]
#   ② 它一共剥掉了哪几维？答：第1维和第2维
