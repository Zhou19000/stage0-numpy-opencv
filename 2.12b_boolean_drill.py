# ============ 第 3 题：np.clip 两头都要夹 + 布尔就地赋值 ============
c = np.array([-10, 25, 700, 480, 1000])
print(np.clip(c, 0, 640))          # 预测: (0,25,640,480,640) (小于 0 的抬起来、大于 640 的压下去，两头都管)
print(np.clip(c, 0, 640).shape)    # 预测:(5,)
p = np.array([[300, -5, 40],
              [900, 200, 999]])
p[p > 255] = 255                   # 布尔就地赋值（先把越界的找出来，再统一改）
p[p < 0] = 0
print(p)                           # 预测:[[255, 0, 40],[255, 200, 255]]
