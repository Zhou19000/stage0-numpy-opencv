import numpy as np

# ============ 第 1 题：布尔索引三步（比出来 → 遮住 → 挑走）============
v = np.array([12, 5, 30, 8, 21, 3])
m = v > 10
print(v.shape)                 # 预测:(6,)
print(m)                       # 预测:[Ture,False,Ture,False,Ture,False]
print(m.dtype)                 # 预测:bool
print(v[m])                    # 预测:[12,30,21]
print(v[m].shape)              # 预测:(3,)
print(m.sum())                 # 预测:3
print(v[m].sum())              # 预测: 63 (True 当 1 参与求和，那被挑走的值相加是多少？)
print(np.where(v > 10)[0])     # 预测:  [0,2,4]  (不写第二三个参数 = 只要下标)
print(np.where(v > 10, v, 0))  # 预测: [12,0,30,0,21,0] (满足的保留原值，否则填 0)

# ============ 第 2 题：多条件组合（每个条件都要括号！）============
s = np.array([0.9, 0.2, 0.6, 0.95, 0.1, 0.45])
print(s[(s > 0.3) & (s < 0.7)])         # 预测:[0.6,0.45)
print(s[(s < 0.2) | (s > 0.9)])         # 预测: [0.95,0.1] (| 是"并集"，满足任一个就留下)
print(s[~(s > 0.5)])                    # 预测: [0.2,0.1,0.45] (~ 是取反，等价于 s <= 0.5)
print(s[(s > 0.3) & (s < 1.0)].shape)   # 预测: (4,)
