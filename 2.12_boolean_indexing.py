"""
Day9 · 2.12 布尔索引、np.where 与 np.clip

这是第 2 章剩下几节里最"能干活"的一节 —— 目标检测后处理（按置信度筛框、
把框坐标摁回图像范围内）全靠今天这三个工具。

规则还是一样：每个 print 后面先把"预测"写完（写不出就打 ⚠️），再整体运行对答案。
维度、索引一律用"嵌套括号 + 维度编号 + 剥皮公式"那套说法，不用行/列/层。
"""
import numpy as np

# ============ 第一部分：布尔索引认脸 ============
scores = np.array([0.9, 0.2, 0.6, 0.95, 0.1])
mask = scores > 0.5                      # 逐元素比较，得到一个"同形状"的布尔数组
print(mask)                              # 预测:[True,False,True,True,False]
print(mask.shape, mask.dtype)            # 预测:(5,) bool
print(scores[mask])                      # 预测:[0.9,0.6,0.95]
print(scores[mask].shape)                # 预测:(3,)
print(mask.sum())                        # 预测:3
print(np.where(scores > 0.5)[0])         # 预测:[0,2,3]
print(np.where(scores > 0.5, 1, 0))      # 预测:[1,0,1,1,0]

# ============ 第二部分：同一个 mask 同时筛多行 + 多条件组合 ============
boxes = np.array([[10, 10, 50, 50],
                  [20, 20, 60, 60],
                  [0, 0, 5, 5],
                  [100, 100, 150, 150],
                  [1, 1, 2, 2]])
print(boxes[mask].shape)                 # 预测:(3,4)
print(boxes[mask])                       # 预测: [[10, 10, 50, 50],[0, 0, 5, 5],[100, 100, 150, 150]]
print(scores[(scores > 0.15) & (scores < 0.8)])   # 预测:[ 0.2, 0.6]
print(scores[(scores > 0.15) | (scores > 0.9)])   # 预测:[0.9, 0.2, 0.6, 0.95]
print(boxes[:, [0, 2]].shape)            # 预测:  (5,2) (花式索引：一次取不连续的两列)

# ============ 第三部分：np.clip 与布尔赋值 ============
print(np.clip(np.array([-5, 10, 620, 700]), 0, 640))   # 预测:[0,10,620,640]
img = np.array([[10, 250], [300, -20]])
img[img > 255] = 255                     # 布尔索引也能用来"就地赋值"
img[img < 0] = 0
print(img)                               # 预测:[[10, 250], [255, 0]]

